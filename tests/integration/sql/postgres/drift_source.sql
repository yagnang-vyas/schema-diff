DROP SCHEMA IF EXISTS drift_source CASCADE;
CREATE SCHEMA drift_source;
SET search_path = drift_source;

CREATE TYPE status_enum AS ENUM ('active', 'inactive', 'pending');

CREATE TABLE users (
    id          serial PRIMARY KEY,
    email       varchar(255) NOT NULL,
    name        text,
    status      status_enum NOT NULL DEFAULT 'active',
    bio         text,
    handle      text COLLATE "C",
    full_label  text GENERATED ALWAYS AS (name || '!') STORED,
    CONSTRAINT users_email_key UNIQUE (email)
);
COMMENT ON COLUMN users.email IS 'login email';
CREATE INDEX idx_users_status ON users (status);

CREATE TABLE orders (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id   integer NOT NULL,
    total     numeric(10,2) NOT NULL DEFAULT 0,
    note      varchar(100),
    placed_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT orders_user_fkey FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT orders_total_check CHECK (total >= 0)
);
CREATE INDEX idx_orders_user_placed ON orders (user_id, placed_at);
CREATE INDEX idx_orders_open ON orders (placed_at) WHERE total > 0;

CREATE TABLE products (
    sku   text PRIMARY KEY,
    name  text NOT NULL,
    price numeric(8,2) NOT NULL,
    qty   integer NOT NULL,
    CONSTRAINT products_qty_check CHECK (qty >= 0)
);
CREATE INDEX idx_products_name ON products USING btree (name);
CREATE UNIQUE INDEX idx_products_sku_price ON products (sku, price);

CREATE TABLE tags (
    id  integer NOT NULL,
    tag text NOT NULL,
    PRIMARY KEY (id)
);

CREATE TABLE audit_log (
    id      integer PRIMARY KEY,
    message text
);

-- Written differently on each side, but logically identical: must report nothing.
CREATE TABLE equivalent_forms (
    id         int4 PRIMARY KEY,
    label      character varying(50) NOT NULL DEFAULT 'n/a'::character varying,
    created_at timestamp without time zone NOT NULL DEFAULT now(),
    ratio      double precision DEFAULT 1.5,
    flag       boolean NOT NULL DEFAULT true,
    CONSTRAINT equivalent_forms_ratio_check CHECK ((ratio > 0::double precision))
);

CREATE VIEW active_users AS SELECT id, email FROM users WHERE status = 'active';
CREATE VIEW order_totals AS SELECT user_id, sum(total) AS total FROM orders GROUP BY user_id;
